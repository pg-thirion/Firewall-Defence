import { test, expect } from '@playwright/test';
test.beforeEach(async ({ page }) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  await page.goto('/');
  await expect(page.locator('#cash')).toHaveText('350');
  await expect(page.locator('.tile')).toHaveCount(140);
  await expect(page.locator('.defence')).toHaveCount(9);
  await expect(page.locator('#start')).toBeEnabled();
  page.on('close', () => {});
  test.info().annotations.push({ type: 'console', description: 'Browser error monitoring enabled' });
  page.errors = errors;
});
test.afterEach(async ({ page }) => { expect(page.errors || []).toEqual([]); });
test('deploy, inspect, upgrade, sell and block invalid placement', async ({ page }) => {
  const tile = page.locator('[data-x="2"][data-y="1"]');
  await page.locator('[data-type="firewall"]').click();
  await tile.click();
  await expect(tile).toContainText('FW');
  await expect(page.locator('#cash')).toHaveText('250');
  await expect(page.locator('[data-x="0"][data-y="2"]')).toBeDisabled();
  await tile.click();
  await expect(page.locator('#inspector')).toContainText('Firewall');
  await page.locator('#upgrade').click();
  await expect(tile).toContainText('L2');
  await expect(page.locator('#cash')).toHaveText('135');
  await expect(page.locator('#upgrade')).toBeDisabled();
  await page.locator('#target').selectOption('strong');
  await expect(page.locator('#target')).toHaveValue('strong');
  await page.locator('#sell').click();
  await expect(page.locator('#cash')).toHaveText('274');
  await expect(tile).not.toHaveClass(/built/);
});
