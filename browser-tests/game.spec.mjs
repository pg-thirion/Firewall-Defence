import { test, expect } from '@playwright/test';
test.beforeEach(async ({ page }) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  await page.goto('/');
  await expect(page.locator('#cash')).toHaveText('350');
  await expect(page.locator('.tile')).toHaveCount(140);
  await expect(page.locator('.defence')).toHaveCount(6);
  await expect(page.locator('#start')).toBeEnabled();
  page.on('close', () => {});
  test.info().annotations.push({ type: 'console', description: 'Browser error monitoring enabled' });
  page.errors = errors;
});
test.afterEach(async ({ page }) => { expect(page.errors || []).toEqual([]); });
test('deploy, inspect, upgrade, sell and block invalid placement', async ({ page }) => {
  const tile = page.locator('[data-x="2"][data-y="1"]');
  await page.locator('[data-type="firewall"]').click();
  await tile.click();
  await expect(tile).toContainText('FW');
  await expect(page.locator('#cash')).toHaveText('250');
  await expect(page.locator('[data-x="0"][data-y="2"]')).toBeDisabled();
  await tile.click();
  await expect(page.locator('#inspector')).toContainText('Firewall');
  await page.locator('#upgrade').click();
  await expect(tile).toContainText('L2');
  await expect(page.locator('#cash')).toHaveText('135');
  await expect(page.locator('#upgrade')).toBeDisabled();
  await page.locator('#target').selectOption('strong');
  await expect(page.locator('#target')).toHaveValue('strong');
  await page.locator('#sell').click();
  await expect(page.locator('#cash')).toHaveText('274');
  await expect(tile).not.toHaveClass(/built/);
});
test('start, pause, resume, speed and manual', async ({ page }) => {
  await page.locator('[data-type="firewall"]').click();
  await page.locator('[data-x="2"][data-y="1"]').click();
  await page.locator('#start').click();
  await expect(page.locator('#wave')).toHaveText('1 / 15');
  await expect(page.locator('#status')).toHaveText('THREATS ACTIVE');
  await expect(page.locator('#start')).toBeDisabled();
  await page.locator('[data-speed="3"]').click();
  await expect(page.locator('[data-speed="3"]')).toHaveAttribute('aria-pressed','true');
  await page.locator('#pause').click();
  await expect(page.locator('#status')).toHaveText('PAUSED');
  await page.locator('#pause').click();
  await expect(page.locator('#status')).toHaveText('THREATS ACTIVE');
  await page.locator('#help').click();
  await expect(page.locator('#manual')).toBeVisible();
  await expect(page.locator('#status')).toHaveText('PAUSED');
  await page.locator('#close').click();
  await expect(page.locator('#manual')).not.toBeVisible();
});
test('mission settings and confirmation', async ({ page }) => {
  await page.locator('#map').selectOption('2');
  await page.locator('#difficulty').selectOption('hard');
  await page.locator('#mode').selectOption('endless');
  await page.locator('#apply').click();
  await expect(page.locator('#mapname')).toHaveText('Data Centre');
  await expect(page.locator('#cash')).toHaveText('300');
  await expect(page.locator('#wave')).toHaveText('0 / ∞');
  await page.locator('[data-type="firewall"]').click();
  await page.locator('[data-x="1"][data-y="1"]').click();
  page.once('dialog', d => d.dismiss());
  await page.locator('#new').click();
  await expect(page.locator('#cash')).toHaveText('200');
  page.once('dialog', d => d.accept());
  await page.locator('#new').click();
  await expect(page.locator('#cash')).toHaveText('300');
  await expect(page.locator('.tile.built')).toHaveCount(0);
});
